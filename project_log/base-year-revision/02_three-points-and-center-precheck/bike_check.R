suppressMessages({library(sf);library(dplyr);library(cppRouting)})
load("data/osm/link10.xdr"); load("data/osm/node10.xdr"); load("data/dists0.bike.xdr")
cat("dists0.bike dim:", dim(dists0.bike), "\n"); print(dists0.bike[1:3,1:4])
l <- link10 %>% mutate(FFtime=linklen/15*60/1e3)
nodes <- data.frame(node10$ID, st_coordinates(node10)); names(nodes) <- c("Node","X","Y")
g <- makegraph(df = l[,c("ID1","ID2","FFtime")] %>% st_drop_geometry(), directed = TRUE, coords = nodes)
z <- rownames(dists0.bike); ce <- colnames(dists0.bike)
cat("zones in graph:", mean(z %in% nodes$Node), " centers in graph:", mean(ce %in% nodes$Node), "\n")
m <- get_distance_matrix(g, from = z, to = ce, algorithm = "mch")
dd <- as.vector(m) - as.vector(dists0.bike[rownames(m), colnames(m)])
cat("再現の差（分）: 要約\n"); print(summary(dd)); cat("一致率(|差|<0.01):", mean(abs(dd)<0.01, na.rm=TRUE), "\n")
